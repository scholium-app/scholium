#!/usr/bin/env python3
"""Deterministic original fixtures for round 2 (MIT OR Apache-2.0, repository license).

- `mixed`: ctexart article mixing Chinese, English and math (sections, inline and display math,
  `\\eqref`, lists, theorems); `--pages` is approximate (sections of 6 paragraphs take
  about 1.75 pages; the drivers record the real page count). Compiles with LuaLaTeX (E3/E5) and
  XeLaTeX (E7) because ctex picks its backend from the engine.
- `pdflatex`: the same structure in English with the default Computer Modern fonts (E7).
- `tikz`: an article whose second page holds TikZ pictures (E4 PDF fallback).

Every paragraph of `mixed` and `pdflatex` carries one marker word `QZ<two letters>` (no f/i/l,
so no ligature) that occurs once in the document; E5 uses them as ground truth.
"""

import argparse
import itertools
import random
from pathlib import Path

ZH = [
    "实时预览把每一次击键尽快变成页面上的变化",
    "排版引擎在后台完成整篇编译，前台只重排正在编辑的段落",
    "段落的断行只取决于它自己的文字和当时生效的参数",
    "交叉引用、目录和浮动体的位置属于全局信息，需要整篇编译才能确定",
    "中文与 English 混排时，标点挤压和字间距都要与命令行构建一致",
    "宿主程序只解析受限的消息，不执行文档里的任何代码",
    "沙箱让排版进程看不到用户目录，也连不上网络",
    "如果某个段落无法实时更新，它会等待下一次后台编译",
    "逐字形比较可以发现极小的位置偏差",
    "长文档的后台编译可能需要几秒钟，但击键不应因此卡顿",
    "公式编号由计数器决定，计数器的状态来自上一次完整编译",
    "定理环境、列表和显示公式各自构成一个排版单元",
    "字体缓存决定了第一次布局需要多长时间",
    "页面上的点击需要回到源码中的某个字节位置",
    "我们记录每一步的时间戳，再计算中位数和九十五分位数",
]
EN = [
    "the live engine keeps the preamble loaded",
    "a background pass settles cross-references",
    "every glyph is compared with the PDF",
    "the host draws the display list into a texture",
    "edits arrive as byte ranges in UTF-8",
    "convergence is reported with every layout",
]
MATH = [r"$E=mc^2$", r"$\alpha+\beta=\gamma$", r"$x_i^2$", r"$\sum_{k=1}^{n} k$", r"$f(x)=\sin x$",
        r"$a\le b$", r"$\sqrt{2}$", r"$n!$"]
EN_SENT = [
    "Real-time preview turns every keystroke into a visible change on the page",
    "The background pass compiles the whole document while the foreground retypesets one paragraph",
    "Line breaks of a paragraph depend only on its own text and the parameters in force",
    "Cross-references and float placement are global and need a full compile",
    "The host only parses restricted messages and never runs document code",
    "A unit that cannot go live waits for the next background pass",
    "Glyph-by-glyph comparison catches tiny position differences",
    "Equation numbers come from counters recorded by the previous full compile",
]
LETTERS = "abcdeghjkmnopqrstuvwxyz"
PARAGRAPHS_PER_SECTION = 6
# A section (6 paragraphs, an equation, a list, a theorem) fills about 1.75 pages.
SECTIONS_PER_PAGE = 0.57


def markers():
    for a, b in itertools.product(LETTERS, repeat=2):
        yield f"QZ{a}{b}"


def zh_paragraph(rng, marker):
    parts = []
    for i in range(rng.randint(4, 6)):
        sentence = rng.choice(ZH)
        if i == 1:
            sentence += f"，{marker} 标记这一段"
        if rng.random() < 0.4:
            sentence += f"，例如 {rng.choice(MATH)}"
        if rng.random() < 0.3:
            sentence += f"（{rng.choice(EN)}）"
        parts.append(sentence + "。")
    return "".join(parts)


def en_paragraph(rng, marker):
    parts = []
    for i in range(rng.randint(4, 6)):
        sentence = rng.choice(EN_SENT)
        if i == 1:
            sentence += f", marked by {marker}"
        if rng.random() < 0.4:
            sentence += f", for example {rng.choice(MATH)}"
        parts.append(sentence + ".")
    return " ".join(parts)


def body(pages, paragraph, theorem, seed):
    rng, mark, out = random.Random(seed), markers(), []
    sections = max(1, round(pages * SECTIONS_PER_PAGE))
    per_section = 3 if pages <= 1 else PARAGRAPHS_PER_SECTION
    for s in range(1, sections + 1):
        out.append(f"\\section{{{'第 ' + str(s) + ' 部分' if theorem == '定理' else 'Part ' + str(s)}}}"
                   f"\\label{{sec:{s}}}\n")
        for p in range(per_section):
            out.append(paragraph(rng, next(mark)) + "\n")
            if p == 1:
                out.append(f"\\begin{{equation}}\\label{{eq:{s}}}\n"
                           f"  \\int_0^{{{s}}} x^2\\,dx = \\frac{{{s}^3}}{{3}}\n\\end{{equation}}\n"
                           f"{paragraph(rng, next(mark))} (\\eqref{{eq:{s}}}, \\ref{{sec:{s}}})\n")
            if p == 3:
                out.append("\\begin{itemize}\n" + "".join(
                    f"  \\item {rng.choice(EN_SENT)} {rng.choice(MATH)}\n" for _ in range(3))
                    + "\\end{itemize}\n")
            if p == 4:
                out.append(f"\\begin{{theorem}}{paragraph(rng, next(mark))}\\end{{theorem}}\n")
        out.append("")
    return "\n".join(out)


def mixed(pages, seed=7):
    head = ("% Generated by spikes/rtex-eval/gen_fixtures.py (original text, MIT OR Apache-2.0).\n"
            "\\documentclass{ctexart}\n\\usepackage{amsmath,amssymb,amsthm}\n"
            "\\newtheorem{theorem}{定理}\n\\begin{document}\n")
    return head + body(pages, zh_paragraph, "定理", seed) + "\\end{document}\n"


def pdflatex(pages, seed=11):
    head = ("% Generated by spikes/rtex-eval/gen_fixtures.py (original text, MIT OR Apache-2.0).\n"
            "\\documentclass{article}\n\\usepackage{amsmath,amssymb,amsthm}\n"
            "\\newtheorem{theorem}{Theorem}\n\\begin{document}\n")
    return head + body(pages, en_paragraph, "Theorem", seed) + "\\end{document}\n"


def tikz():
    rng = random.Random(3)
    text = "\n\n".join(en_paragraph(rng, m) for m in itertools.islice(markers(), 8))
    pictures = r"""
\begin{center}
\begin{tikzpicture}[scale=1.2]
  \draw[->] (-0.2,0) -- (4.2,0) node[right] {$x$};
  \draw[->] (0,-0.2) -- (0,3.2) node[above] {$y$};
  \draw[thick,blue,domain=0:4,samples=60] plot (\x,{0.18*\x*\x});
  \draw[red,dashed] (0,0) -- (4,3);
  \foreach \x in {1,2,3} \draw (\x,0.1) -- (\x,-0.1) node[below] {\x};
  \fill[green!40!black] (2,0.72) circle (2pt) node[above left] {$P$};
\end{tikzpicture}
\end{center}

\begin{center}
\begin{tikzpicture}
  \foreach \r in {0.4,0.8,...,2.0} \draw[gray] (0,0) circle (\r);
  \draw[fill=orange!30] (0,0) -- (30:2) arc (30:110:2) -- cycle;
  \node at (0,-2.4) {A sector over concentric circles};
\end{tikzpicture}
\end{center}
"""
    return ("% Generated by spikes/rtex-eval/gen_fixtures.py (original, MIT OR Apache-2.0).\n"
            "\\documentclass{article}\n\\usepackage{tikz}\n\\begin{document}\n"
            f"{text}\n\\clearpage\n{pictures}\n"
            "Text after the pictures keeps the page mixed.\n\\end{document}\n")


def write(kind, pages, out):
    text = {"mixed": lambda: mixed(pages), "pdflatex": lambda: pdflatex(pages), "tikz": tikz}[kind]()
    out.mkdir(parents=True, exist_ok=True)
    (out / "main.tex").write_text(text)
    return out / "main.tex"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("kind", choices=("mixed", "pdflatex", "tikz"))
    parser.add_argument("--pages", type=int, default=5)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()
    print(write(args.kind, args.pages, args.out))


if __name__ == "__main__":
    main()
